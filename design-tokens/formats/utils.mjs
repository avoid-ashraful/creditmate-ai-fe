import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import prettier from 'prettier';

/**
 * Shared helpers for the CreditMate design token formats.
 *
 * Everything here is deliberately free of Style Dictionary internals so the
 * formats stay stable across Style Dictionary upgrades.
 */

const here = dirname(fileURLToPath(import.meta.url));

/** Root of the frontend project (directory that holds package.json). */
export const projectRoot = resolve(here, '..', '..');

/**
 * Prettier options resolved from the project `.prettierrc`.
 *
 * Generated token files are consumed by both humans and tooling, so the build
 * output is formatted with the exact same rules as hand written code. That keeps
 * `npm run check-format` and `npm run check-lint` green without ignoring
 * generated files, and makes the build byte-for-byte reproducible.
 */
export const PROJECT_PRETTIER_CONFIG = prettier.resolveConfig.sync(projectRoot, {
  editorconfig: false,
  useCache: false,
});

export function formatWithPrettier(code, parser) {
  return prettier.format(code, { ...PROJECT_PRETTIER_CONFIG, parser });
}

/** Builds a nested object of raw token values out of a flat token list. */
export function nestTokens(tokens) {
  const root = {};

  for (const token of tokens) {
    const path = [...token.path];
    const leaf = path.pop();

    let node = root;
    for (const key of path) {
      if (typeof node[key] !== 'object' || node[key] === null) {
        node[key] = {};
      }
      node = node[key];
    }

    node[leaf] = token.value;
  }

  return root;
}

/** Removes quotes around plain object keys so generated code reads naturally. */
export function unquoteKeys(code) {
  return code.replace(/"([A-Za-z_$][A-Za-z0-9_$]*)":/g, '$1:');
}

/**
 * Tokens are emitted in source order (sorted token files, authored key order),
 * not alphabetically, so the published ramps read `xs, sm, md, ...` and
 * `50, 100, 200, ...`. JSON key order is stable, and `npm run tokens:check`
 * fails the build if it ever becomes non-deterministic.
 */

/**
 * Maps the DTCG token types used in `design-tokens/tokens/*.json` onto the type
 * names understood by the Tokens Studio for Figma plugin.
 */
const FIGMA_TYPES = {
  color: 'color',
  dimension: 'sizing',
  spacing: 'spacing',
  fontFamily: 'fontFamilies',
  fontSizes: 'fontSizes',
  fontWeights: 'fontWeights',
  lineHeights: 'lineHeights',
  borderRadius: 'borderRadius',
  shadow: 'boxShadow',
  duration: 'duration',
  cubicBezier: 'transitionTimingFunction',
  transitionProperty: 'other',
  transition: 'other',
  letterSpacing: 'letterSpacing',
  // DTCG `gradient` tokens carry a CSS `linear-gradient()` string here, which
  // Tokens Studio stores as a generic token rather than a colour.
  gradient: 'other',
};

export function figmaType(token) {
  return FIGMA_TYPES[token?.type] ?? 'other';
}

