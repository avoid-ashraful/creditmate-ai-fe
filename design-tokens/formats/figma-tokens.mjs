import { figmaType, formatWithPrettier } from './utils.mjs';

import { shadowValue } from './shadow.mjs';

/**
 * Style Dictionary format: `figma/tokens`
 *
 * Emits a Tokens Studio for Figma compatible token set. The plugin imports it
 * through "Sync" -> "Import JSON", which turns every token into a local Figma
 * style/variable that stays linked to the values in `design-tokens/tokens`.
 *
 * Shape: { "<set name>": { "<token path>": { value, type, description? } } }
 */
export default function figmaTokens({ dictionary, options = {} }) {
  const setName = options.setName ?? 'global';

  const tree = {};
  for (const token of dictionary.allTokens) {
    const path = [...token.path];
    const leaf = path.pop();

    let node = tree;
    for (const key of path) {
      if (typeof node[key] !== 'object' || node[key] === null) {
        node[key] = {};
      }
      node = node[key];
    }

    const isShadow = token.type === 'shadow';
    const { type, value } = isShadow
      ? shadowValue(token.value)
      : { type: figmaType(token), value: token.value };

    const entry = {
      value,
      type,
    };
    const description = token.description ?? token.comment;
    if (description) {
      entry.description = description;
    }

    node[leaf] = entry;
  }

  const payload = {
    $description:
      'CreditMate AI design tokens. Generated by Style Dictionary from ' +
      'design-tokens/tokens/*.json; do not edit directly.',
    $extensions: {
      'com.creditmate.generator': 'style-dictionary',
      'com.creditmate.source': 'design-tokens/tokens/*.json',
    },
    [setName]: tree,
  };

  const json = `${JSON.stringify(payload, null, 2)}\n`;
  return formatWithPrettier(json, 'json');
}
