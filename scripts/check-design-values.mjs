#!/usr/bin/env node
/**
 * Design-values lint for the UI/UX redesign (plan Section 3.1).
 *
 * Components must consume design tokens only. Hand-written CSS/TSX may not
 * introduce raw colour values, off-scale breakpoints, raw spacing values or
 * `transition: all`. This script enforces that without stylelint, following
 * the repo's existing custom-check idiom (see scripts/verify-tokens.mjs).
 *
 * Zones
 * -----
 * STRICT ZONE (zero tolerance, any violation fails):
 *   - src/components/ui/**    (new design-system foundation)
 *   - src/components/shell/** (new app shell)
 *   Missing directories are skipped gracefully — the zones take effect as
 *   soon as the code lands.
 *
 * LEGACY ZONE (ratchet):
 *   - everything else under src/**
 *   Existing code carries a lot of design debt (~868 hex literals at the
 *   time this check landed), so legacy files are compared against
 *   scripts/design-values-baseline.json, which stores per-file violation
 *   counts per rule. A legacy file fails only when a count EXCEEDS its
 *   baseline entry (a new violation), or when it has violations and no
 *   baseline entry at all. Debt can only go down: when files improve, the
 *   script says so and suggests re-running --write-baseline to lock the
 *   improvement in.
 *
 * Rules
 * -----
 *   hex-color        #rgb / #rrggbb / #rrggbbaa literals (.css, .ts, .tsx)
 *   color-function   rgb() / rgba() / hsl() / hsla() literals (.css, .ts, .tsx)
 *   breakpoint       @media width values outside the scale
 *                    {480px, 768px, 1024px, 1280px} (.css, .ts, .tsx; only
 *                    width features are checked — prefers-reduced-motion,
 *                    prefers-color-scheme etc. are ignored)
 *   raw-spacing      raw px values (other than 0 and 1px hairlines) in
 *                    margin / padding / gap / inset / top / right / bottom /
 *                    left declarations (.css only; spacing comes from tokens)
 *   transition-all   `transition: all` (.css only; the plan bans it)
 *
 * Exclusions
 * ----------
 *   - src/styles/tokens.css and src/styles/tokens.ts — generated by Style
 *     Dictionary; they are the token definitions themselves.
 *   - Test files (*.test.*) and stories (*.stories.*) in .ts/.tsx — story
 *     fixtures may legitimately pass colour props. Component .css files are
 *     scanned everywhere, including next to tests/stories.
 *   - CSS comments (block comments in every scanned file) are stripped
 *     before scanning, so a hex value mentioned in a comment never counts.
 *     TS/TSX files are otherwise scanned naively (whole file, including
 *     template literals and inline style objects): in the strict zone a hex
 *     literal anywhere is a violation, and in the legacy zone inline-style
 *     hex values are real debt and belong in the baseline.
 *
 * Usage
 * -----
 *   node scripts/check-design-values.mjs                 check everything
 *   node scripts/check-design-values.mjs src/components/ui   check a subtree
 *   node scripts/check-design-values.mjs --write-baseline    regenerate baseline
 *
 * Run with: npm run check-styles
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcRoot = join(projectRoot, 'src');
const baselinePath = join(projectRoot, 'scripts', 'design-values-baseline.json');

const STRICT_PREFIXES = ['src/components/ui/', 'src/components/shell/'];
const GENERATED_FILES = new Set(['src/styles/tokens.css', 'src/styles/tokens.ts']);
const BREAKPOINT_SCALE = new Set([480, 768, 1024, 1280]);
const SPACING_PROPERTIES =
  '(?:margin(?:-(?:top|right|bottom|left|inline|block|inline-start|inline-end|block-start|block-end))?|padding(?:-(?:top|right|bottom|left|inline|block|inline-start|inline-end|block-start|block-end))?|gap|row-gap|column-gap|inset(?:-(?:inline|block|inline-start|inline-end|block-start|block-end))?|top|right|bottom|left)';

const RULES = {
  'hex-color': {
    description: 'hex colour literal — use a colour token instead',
    // Longest alternatives first so #rrggbbaa wins over #rrggbb over #rgb.
    pattern: /#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g,
    appliesTo: ['.css', '.ts', '.tsx'],
  },
  'color-function': {
    description: 'rgb()/hsl() colour literal — use a colour token instead',
    pattern: /\b(?:rgba?|hsla?)\s*\(/g,
    appliesTo: ['.css', '.ts', '.tsx'],
  },
  breakpoint: {
    description: 'off-scale @media width — scale is 480px, 768px, 1024px, 1280px',
    // Handled specially below: values are extracted from @media preludes.
    pattern: null,
    appliesTo: ['.css', '.ts', '.tsx'],
  },
  'raw-spacing': {
    description: 'raw px spacing — use a spacing token instead (0 and 1px allowed)',
    // A spacing declaration whose value contains a px amount other than
    // 0px / 1px. The declaration runs to the next `;` or `}`.
    pattern: new RegExp(`\\b${SPACING_PROPERTIES}\\s*:[^;}]*`, 'g'),
    valuePattern: /-?\d+(?:\.\d+)?px/g,
    appliesTo: ['.css'],
  },
  'transition-all': {
    description: '`transition: all` is banned — name the transitioning properties',
    pattern: /\btransition\s*:\s*all\b/g,
    appliesTo: ['.css'],
  },
};

const args = process.argv.slice(2);
const writeBaseline = args.includes('--write-baseline');
const pathFilter = args.find((arg) => !arg.startsWith('--'));

/** Recursively collect scannable files under a directory. */
function collectFiles(dir, out) {
  if (!existsSync(dir)) return out;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'node_modules') continue;
      collectFiles(full, out);
    } else if (entry.isFile()) {
      out.push(full);
    }
  }
  return out;
}

function isScannable(relPath) {
  if (GENERATED_FILES.has(relPath)) return false;
  if (relPath.endsWith('.css')) return true;
  if (/\.tsx?$/.test(relPath)) {
    if (/\.test\.[^.]+$/.test(relPath) || /\.stories\.[^.]+$/.test(relPath)) return false;
    return true;
  }
  return false;
}

function isStrict(relPath) {
  return STRICT_PREFIXES.some((prefix) => relPath.startsWith(prefix));
}

/** Strip block comments while preserving line numbers (newlines kept). */
function stripComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, (match) => match.replace(/[^\n]/g, ' '));
}

function lineOf(source, index) {
  let line = 1;
  for (let i = 0; i < index; i += 1) {
    if (source.charCodeAt(i) === 10) line += 1;
  }
  return line;
}

function snippetAt(source, index) {
  const start = source.lastIndexOf('\n', index - 1) + 1;
  let end = source.indexOf('\n', index);
  if (end === -1) end = source.length;
  const line = source.slice(start, end).trim();
  return line.length > 120 ? `${line.slice(0, 117)}...` : line;
}

/** Extract off-scale width values from @media preludes. */
function findBreakpointViolations(source) {
  const violations = [];
  const mediaPattern = /@media\b([^{]*)\{/g;
  let match;
  while ((match = mediaPattern.exec(source)) !== null) {
    const prelude = match[1];
    if (!/width/.test(prelude)) continue;
    // Both `(min-width: 768px)` and range syntax `(width >= 768px)`.
    const widthPattern = /width\s*(?::|[<>]=?)\s*(\d+(?:\.\d+)?)px/g;
    let widthMatch;
    while ((widthMatch = widthPattern.exec(prelude)) !== null) {
      const value = Number.parseFloat(widthMatch[1]);
      if (!BREAKPOINT_SCALE.has(value)) {
        violations.push({
          index: match.index + widthMatch.index,
          detail: `${widthMatch[1]}px is not in the breakpoint scale`,
        });
      }
    }
  }
  return violations;
}

/** Scan one file's (comment-stripped) source; returns violations per rule. */
function scanFile(relPath, source) {
  const ext = relPath.slice(relPath.lastIndexOf('.'));
  const violations = [];
  for (const [ruleName, rule] of Object.entries(RULES)) {
    if (!rule.appliesTo.includes(ext)) continue;
    if (ruleName === 'breakpoint') {
      for (const hit of findBreakpointViolations(source)) {
        violations.push({
          rule: ruleName,
          line: lineOf(source, hit.index),
          snippet: snippetAt(source, hit.index),
          detail: hit.detail,
        });
      }
      continue;
    }
    rule.pattern.lastIndex = 0;
    let match;
    while ((match = rule.pattern.exec(source)) !== null) {
      if (ruleName === 'raw-spacing') {
        // One violation per offending px value inside the declaration.
        const values = match[0].match(rule.valuePattern) ?? [];
        for (const value of values) {
          const numeric = Number.parseFloat(value);
          if (numeric === 0 || numeric === 1 || numeric === -1) continue;
          violations.push({
            rule: ruleName,
            line: lineOf(source, match.index),
            snippet: snippetAt(source, match.index),
            detail: `${value} in a spacing declaration`,
          });
        }
        continue;
      }
      violations.push({
        rule: ruleName,
        line: lineOf(source, match.index),
        snippet: snippetAt(source, match.index),
        detail: match[0].trim(),
      });
    }
  }
  return violations;
}

// ---------------------------------------------------------------------------
// Gather files
// ---------------------------------------------------------------------------

const scanRoot = pathFilter ? resolve(projectRoot, pathFilter) : srcRoot;
let files = [];
if (existsSync(scanRoot) && statSync(scanRoot).isFile()) {
  files = [scanRoot];
} else {
  collectFiles(scanRoot, files);
}
files = files
  .map((full) => ({ full, rel: relative(projectRoot, full).split(sep).join('/') }))
  .filter(({ rel }) => isScannable(rel))
  .sort((a, b) => a.rel.localeCompare(b.rel));

// ---------------------------------------------------------------------------
// Scan
// ---------------------------------------------------------------------------

const results = new Map(); // rel -> { violations: [...], counts: {rule: n} }
for (const { full, rel } of files) {
  const source = stripComments(readFileSync(full, 'utf8'));
  const violations = scanFile(rel, source);
  if (violations.length === 0) continue;
  const counts = {};
  for (const violation of violations) {
    counts[violation.rule] = (counts[violation.rule] ?? 0) + 1;
  }
  results.set(rel, { violations, counts });
}

// ---------------------------------------------------------------------------
// --write-baseline: snapshot legacy debt (strict zone is never baselined)
// ---------------------------------------------------------------------------

if (writeBaseline) {
  const baseline = {};
  for (const [rel, { counts }] of results) {
    if (isStrict(rel)) continue;
    baseline[rel] = counts;
  }
  const totals = {};
  let total = 0;
  for (const counts of Object.values(baseline)) {
    for (const [rule, count] of Object.entries(counts)) {
      totals[rule] = (totals[rule] ?? 0) + count;
      total += count;
    }
  }
  const payload = {
    $comment:
      'Legacy design-values debt ratchet. Generated by `node scripts/check-design-values.mjs --write-baseline`. ' +
      'Counts may only go down: check mode fails when a file exceeds its entry here. ' +
      'Re-run --write-baseline after cleaning files up to lock in the improvement.',
    files: baseline,
  };
  writeFileSync(baselinePath, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(
    `Baseline written to scripts/design-values-baseline.json: ` +
      `${Object.keys(baseline).length} legacy files, ${total} violations ` +
      `(${Object.entries(totals)
        .map(([rule, count]) => `${rule}: ${count}`)
        .join(', ')}).`
  );
  process.exit(0);
}

// ---------------------------------------------------------------------------
// Check mode
// ---------------------------------------------------------------------------

let baseline = {};
if (existsSync(baselinePath)) {
  try {
    baseline = JSON.parse(readFileSync(baselinePath, 'utf8')).files ?? {};
  } catch {
    console.error('✗ scripts/design-values-baseline.json is not valid JSON — regenerate it with --write-baseline');
    process.exit(1);
  }
}

const errors = [];
let strictViolationCount = 0;
let legacyDebtTotal = 0;
const legacyTotalsByRule = {};
let improvedFiles = 0;

for (const [rel, { violations, counts }] of results) {
  if (isStrict(rel)) {
    strictViolationCount += violations.length;
    for (const violation of violations) {
      errors.push(
        `✗ ${rel}:${violation.line} [${violation.rule}] ${RULES[violation.rule].description}\n` +
          `    ${violation.snippet}  (${violation.detail})`
      );
    }
    continue;
  }

  // Legacy zone: count current debt, fail only on regression vs baseline.
  for (const [rule, count] of Object.entries(counts)) {
    legacyDebtTotal += count;
    legacyTotalsByRule[rule] = (legacyTotalsByRule[rule] ?? 0) + count;
  }
  const baselineCounts = baseline[rel];
  if (!baselineCounts) {
    errors.push(
      `✗ ${rel} [legacy regression] has design-value violations but no baseline entry — ` +
        `new legacy files may not add design debt:\n` +
        violations
          .map((v) => `    ${rel}:${v.line} [${v.rule}] ${v.snippet}  (${v.detail})`)
          .join('\n')
    );
    continue;
  }
  let improved = false;
  for (const [rule, count] of Object.entries(counts)) {
    const allowed = baselineCounts[rule] ?? 0;
    if (count > allowed) {
      const excess = violations.filter((v) => v.rule === rule);
      errors.push(
        `✗ ${rel} [legacy regression] ${rule}: ${count} violation(s), baseline allows ${allowed}:\n` +
          excess.map((v) => `    ${rel}:${v.line} [${v.rule}] ${v.snippet}  (${v.detail})`).join('\n')
      );
    } else if (count < allowed) {
      improved = true;
    }
  }
  for (const rule of Object.keys(baselineCounts)) {
    if (!(rule in counts)) improved = true;
  }
  if (improved) improvedFiles += 1;
}

// Baseline entries for unscanned-but-existing clean files also count as improved.
for (const rel of Object.keys(baseline)) {
  if (!results.has(rel) && existsSync(join(projectRoot, rel))) improvedFiles += 1;
}

for (const error of errors) console.error(error);

console.log('\nDesign values check');
console.log(`  Files scanned: ${files.length}`);
console.log(
  `  Strict zone (src/components/ui, src/components/shell): ` +
    (strictViolationCount === 0 ? 'clean' : `${strictViolationCount} violation(s)`)
);
console.log(
  `  Legacy debt: ${legacyDebtTotal} violation(s) across ${[...results.keys()].filter((rel) => !isStrict(rel)).length} files ` +
    `(${Object.entries(legacyTotalsByRule)
      .map(([rule, count]) => `${rule}: ${count}`)
      .join(', ') || 'none'})`
);
if (improvedFiles > 0) {
  console.log(
    `  ${improvedFiles} legacy file(s) improved vs the baseline — re-run ` +
      '`node scripts/check-design-values.mjs --write-baseline` and commit the result to lower the ratchet.'
  );
}

if (errors.length > 0) {
  console.error(
    `\n✗ Design values check failed: ${errors.length} problem(s). ` +
      'Use design tokens (src/styles/tokens.css) instead of raw values.'
  );
  process.exit(1);
}

console.log('\n✓ Design values check passed.');
